<script>
function toggleInfo(tabId) {
    document.querySelectorAll('.tab-panel').forEach(panel => {
        panel.classList.add('hidden', 'opacity-0');
        panel.classList.remove('block', 'opacity-100');
    });

    document.querySelectorAll('.tab-trigger').forEach(btn => {
        btn.classList.remove('bg-purple-600', 'text-white');
        btn.classList.add('bg-zinc-900', 'text-zinc-400', 'border-zinc-800');
    });

    const targetPanel = document.getElementById('text-' + tabId);
    targetPanel.classList.remove('hidden');
    setTimeout(() => {
        targetPanel.classList.add('block', 'opacity-100');
    }, 10);

    const targetBtn = document.getElementById('btn-' + tabId);
    targetBtn.classList.add('bg-purple-600', 'text-white');
    targetBtn.classList.remove('bg-zinc-900', 'text-zinc-400', 'border-zinc-800');
}
</script>

